<?php
// Standalone deterministic domain checks, no PHPUnit/database setup required.
require __DIR__.'/../vendor/autoload.php';
use App\Services\EmergencyBedService;
$path = __DIR__.'/../storage/app/emergency-test-'.bin2hex(random_bytes(4)).'.json';
$service = new EmergencyBedService($path,300);
$checks = 0;
function check($condition, $message) { global $checks; if (!$condition) throw new RuntimeException($message); $checks++; }
function requestById($state,$id) { foreach ($state['requests'] as $r) if ($r['id']===$id) return $r; throw new RuntimeException('Missing request'); }
function fails($fn) { try { $fn(); } catch (RuntimeException $e) { return true; } return false; }
try {
    $input=['patient'=>'Accident 01','location'=>'Accident Site','severity'=>'Critical','care'=>'ICU'];
    $first=$service->create($input,'client1');
    $state=$service->state(); $r=requestById($state,$first);
    check(count($state['hospitals'])===5,'Five seeded hospitals');
    check($r['priority']===1,'Self-declared Critical must not increase priority');
    check($r['matches'][0]['id']==='C','Closest compatible hospital C recommended');
    $a=array_values(array_filter($r['matches'],fn($m)=>$m['id']==='A'))[0];
    check(!$a['compatible'],'A rejected because ICU unavailable');
    check(fails(fn()=>$service->requestBed($first,'A')),'Incompatible hospital rejected server-side');
    $service->verify($first,'Critical');$service->requestBed($first,'C');
    $service->verify($first,'Urgent','C');
    check(requestById($service->state(),$first)['severity']==='Urgent','Hospital can update severity of its pending request');
    $service->verify($first,'Critical','C');
    check(fails(fn()=>$service->action($first,'accept','B')),'Locked service enforces hospital scope');
    check(fails(fn()=>$service->requestBed($first,'B',999)),'Locked service enforces patient ownership');
    $service->action($first,'accept','C');
    check(requestById($service->state(),$first)['status']==='Reserved','Acceptance reserves bed');
    $second=$service->create(array_merge($input,['patient'=>'Accident 02']),'client2');$service->verify($second,'Critical');
    check(requestById($service->state(),$second)['matches'][0]['id']==='B','Second Critical uses B, confirmed C not evicted');
    check(fails(fn()=>$service->requestBed($second,'C')),'Confirmed bed protected');
    $service->action($first,'arrive');
    check(fails(fn()=>$service->requestBed($second,'C')),'Occupied bed protected');
    check(fails(fn()=>$service->action($first,'reject')),'Occupied request cannot be rejected');
    $service->reset();
    $stable=$service->create(array_merge($input,['patient'=>'Stable 01','severity'=>'Stable']),'s');$service->requestBed($stable,'C');
    check(fails(fn()=>$service->action($stable,'accept')),'Hospital cannot accept unverified severity');
    $critical=$service->create(array_merge($input,['patient'=>'Critical 02']),'c');
    check(fails(fn()=>$service->requestBed($critical,'C')),'Unverified Critical cannot reclaim hold');
    $service->verify($critical,'Critical');$service->requestBed($critical,'C');
    $state=$service->state();
    check(requestById($state,$stable)['status']==='Released','Lower priority temporary hold released');
    check($state['requests'][0]['id']===$critical,'Verified Critical sorted first');
    $service->requestBed($stable,'B');$service->verify($stable,'Stable');$service->action($stable,'accept');
    $raw=json_decode(file_get_contents($path),true);
    foreach($raw['requests'] as &$r) if($r['id']===$stable || $r['id']===$critical)$r['expires_at']=time()-1;
    unset($r);file_put_contents($path,json_encode($raw));$state=$service->state();
    check(requestById($state,$stable)['status']==='Expired','Confirmed reservation expires');
    check(requestById($state,$critical)['status']==='Expired','Temporary hold expires');
    check(requestById($state,$critical)['matches'][0]['available']===1,'Expired ICU hold returns capacity');
    $service->reset();
    for($i=0;$i<5;$i++)$service->create(array_merge($input,['patient'=>'Rate '.$i]),'same-ip');
    check(fails(fn()=>$service->create(array_merge($input,['patient'=>'Rate 6']),'same-ip')),'Sixth request rate limited');
    check(fails(fn()=>$service->create(array_merge($input,['patient'=>'Rate 0']),'other-ip')),'Duplicate active patient blocked');
    $service->reset();
    $service->manageHospital('C','capacity',['care'=>'ICU','total'=>5]);
    $c=collect($service->state()['hospitals'])->firstWhere('id','C');
    check(count(array_filter($c['beds'],fn($b)=>$b['care']==='ICU'))===5,'Hospital capacity adds available beds');
    check(fails(fn()=>$service->manageHospital('C','capacity',['care'=>'ICU','total'=>0])),'Capacity protects occupied beds');
    $service->manageHospital('C','blood',['blood_type'=>'A+','units'=>12]);
    $state=$service->state();
    check(collect($state['hospitals'])->firstWhere('id','C')['blood']['A+']===12,'Blood stock saved for own hospital');
    check(!isset(collect($state['hospitals'])->firstWhere('id','B')['blood']['A+']),'Blood update leaves other hospital unchanged');
    check(fails(fn()=>$service->manageHospital('C','blood',['blood_type'=>'A+','units'=>-1])),'Negative blood stock rejected');
    check(fails(fn()=>$service->manageHospital('C','discharge',['bed_id'=>'B-ICU-O'])),'Cross-hospital discharge rejected');
    $service->manageHospital('C','discharge',['bed_id'=>'C-ICU-O']);
    check(collect(collect($service->state()['hospitals'])->firstWhere('id','C')['beds'])->firstWhere('id','C-ICU-O')['status']==='Available','Discharge frees occupied bed');
    $managed=$service->create($input,'management-test',42);$service->verify($managed,'Critical','C');$service->requestBed($managed,'C',42);$service->action($managed,'accept','C');
    $assigned=requestById($service->state(),$managed)['bed_id'];
    check(fails(fn()=>$service->manageHospital('C','discharge',['bed_id'=>$assigned])),'Reserved bed cannot be discharged');
    $service->action($managed,'arrive','C');
    $service->manageHospital('C','discharge',['bed_id'=>$assigned]);
    check(requestById($service->state(),$managed)['status']==='Discharged','Discharge updates linked patient admission');
    $service->manageHospital('C','settings',['status'=>'Offline','contact'=>'123','address'=>'Demo address']);
    check(!collect(requestById($service->state(),$managed)['matches'])->firstWhere('id','C')['compatible'],'Offline hospital excluded from matching');
    check(collect($service->state()['hospitals'])->firstWhere('id','B')['status']==='Open','Settings update preserves other hospitals');
    $service->inventoryCrud('C','inventory','create',null,['care'=>'General','name'=>'CRUD test bed']);
    $c=collect($service->state()['hospitals'])->firstWhere('id','C');
    $crudBed=collect($c['beds'])->firstWhere('name','CRUD test bed');
    check($crudBed['status']==='Available','CRUD bed creation creates available bed');
    $service->inventoryCrud('C','inventory','update',$crudBed['id'],['care'=>'ICU','name'=>'Edited bed']);
    check(collect(collect($service->state()['hospitals'])->firstWhere('id','C')['beds'])->firstWhere('id',$crudBed['id'])['care']==='ICU','CRUD bed edit changes care type');
    check(fails(fn()=>$service->inventoryCrud('B','inventory','delete',$crudBed['id'],[])),'CRUD rejects cross-hospital record deletion');
    check(fails(fn()=>$service->inventoryCrud('C','inventory','delete','C-General-O',[])),'CRUD protects occupied bed deletion');
    $service->inventoryCrud('C','inventory','delete',$crudBed['id'],[]);
    check(!collect(collect($service->state()['hospitals'])->firstWhere('id','C')['beds'])->firstWhere('id',$crudBed['id']),'CRUD bed deletion removes available bed');
    $service->inventoryCrud('C','blood','create',null,['blood_type'=>'AB-','units'=>10]);
    check(fails(fn()=>$service->inventoryCrud('C','blood','create',null,['blood_type'=>'AB-','units'=>20])),'CRUD blood creation rejects duplicate group');
    $service->inventoryCrud('C','blood','update','AB-',['blood_type'=>'O-','units'=>7]);
    $c=collect($service->state()['hospitals'])->firstWhere('id','C');
    check($c['blood']['O-']===7 && !isset($c['blood']['AB-']),'CRUD blood edit updates group and units');
    check(fails(fn()=>$service->inventoryCrud('B','blood','delete','O-',[])),'CRUD blood delete scoped to hospital');
    $service->inventoryCrud('C','blood','delete','O-',[]);
    check(!isset(collect($service->state()['hospitals'])->firstWhere('id','C')['blood']['O-']),'CRUD blood delete removes own record');
    echo "PASS: $checks emergency workflow checks\n";
} finally { foreach ([$path,$path.'.lock',$path.'.tmp'] as $f) if(file_exists($f))unlink($f); }
